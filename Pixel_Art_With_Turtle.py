PIXEL_SIZE = 10


def draw_pixel(x, y, color):
    t.penup()
    t.goto(x, y)
    t.pendown()
    t.color(color, color)
    t.begin_fill()
    for side in range(4):
        t.forward(PIXEL_SIZE)
        t.right(90)
    t.end_fill()


def draw_row(start_x, start_y):
    for i in range(40):
        if i % 3 == 0:
            color = "dimgray"
        elif i % 3 == 1:
            color = "darkgoldenrod"
        else:
            color = "gray"

        x = start_x + i * PIXEL_SIZE
        draw_pixel(x, start_y, color)


