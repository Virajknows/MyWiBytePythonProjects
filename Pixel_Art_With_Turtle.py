def draw_picture(grid, start_x, start_y):
    for row in range(len(grid)):
        for col in range(len(grid[row])):
            value = grid[row][col]
            if value == 1:
                color = "white"
            elif value == 2:
                color = "rosybrown"
            elif value == 3:
                color = "steelblue"
            elif value == 4:
                color = "midnightblue"
            elif value == 5:
                color = "darkslateblue"
            elif value == 6:
                color = "forestgreen"
            elif value == 7:
                color = "darkgreen"
            elif value == 8:
                color = "saddlebrown"
            elif value == 9:
                color = "goldenrod"
            elif value == 10:
                color = "darkgoldenrod"
            elif value == 11:
                color = "dimgray"
            elif value == 12:
                color = "gray"
            elif value == 13:
                color = "plum"
            elif value == 14:
                color = "lavender"
            elif value == 15:
                color = "lightsteelblue"
            else:
                continue
            x = start_x + col * PIXEL_SIZE
            y = start_y - row * PIXEL_SIZE
            draw_pixel(x, y, color)


